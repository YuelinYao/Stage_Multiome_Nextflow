# Validate small task JSONs with the same reader used by scripts 05–08 and 12.
# Run from the repository root: Rscript tests/process_settings.R [Nextflow work dir]
env <- new.env(parent = globalenv())
for (expr in parse("scripts/00_common.R"))
  if (is.call(expr) && identical(expr[[1]], as.name("<-"))) eval(expr, env)
expect_error <- function(expr) stopifnot(inherits(tryCatch(force(expr), error = identity), "error"))
file <- tempfile(fileext = ".json")
read_task <- function(value, sample = "WT_1", process = value$process) {
  jsonlite::write_json(value, file, auto_unbox = TRUE, null = "null")
  env$read_pipeline_config(file, sample, process = process)
}
full <- jsonlite::fromJSON("examples/pipeline_settings.example.json", simplifyVector = FALSE)
review <- list(process = "review_QC_cluster", thresholds = full$thresholds,
               review_QC_cluster = full$review_QC_cluster)
stopifnot(identical(read_task(review)$review_QC_cluster$RNA_dims, 1:20))
doublet <- list(process = "doublet", thresholds = full$thresholds, doublet = full$doublet)
doublet$doublet$expected_rate <- 0.04
doublet$doublet$exclude_clusters <- list(WT_1 = list("2", "4"))
actual <- read_task(doublet)
stopifnot(actual$doublet$expected_rate == 0.04,
          identical(actual$doublet$exclude_clusters, c("2", "4")),
          isTRUE(actual$doublet$remove_mf_doublets))
# remove_mf_doublets defaults to true, accepts false and rejects non-logical values.
doublet$doublet$remove_mf_doublets <- NULL
stopifnot(isTRUE(read_task(doublet)$doublet$remove_mf_doublets))
doublet$doublet$remove_mf_doublets <- FALSE
stopifnot(identical(read_task(doublet)$doublet$remove_mf_doublets, FALSE))
doublet$doublet$remove_mf_doublets <- "yes"
expect_error(read_task(doublet))
doublet$doublet$remove_mf_doublets <- TRUE
# Step 09 variant thresholds: task settings, defaults and invalid values.
mgatk <- list(process = "MGATK", MGATK = list(vmr = 0.02, strand_correlation = 0.7, n_cells_conf_detected = 100))
stopifnot(isTRUE(all.equal(read_task(mgatk)$MGATK, list(vmr = 0.02, strand_correlation = 0.7, n_cells_conf_detected = 100))))
stopifnot(read_task(list(process = "MGATK", MGATK = list(vmr = 0.05)))$MGATK$n_cells_conf_detected == 300)
for (bad in list(list(vmr = 0), list(strand_correlation = 2), list(n_cells_conf_detected = 2.5), list(other = 1)))
  expect_error(read_task(list(process = "MGATK", MGATK = bad)))
# Stage tasks need no QC bounds, exclusions or settings from other stages.
rna <- list(process = "RNA_processing", RNA_processing = full$RNA_processing,
            component_count = 55)
stopifnot(read_task(rna)$component_count == 55L)
atac <- list(process = "ATAC_processing", ATAC_processing = full$ATAC_processing,
             component_count = 40)
stopifnot(read_task(atac)$component_count == 40L)
atac$ATAC_processing$integrate_atac <- FALSE
atac$ATAC_processing$ATAC_integrate_dims <- NULL
atac$ATAC_processing$ATAC_dims <- "2:65"
atac$component_count <- 80
stopifnot(read_task(atac)$component_count == 80L)
for (rna_on in c(FALSE, TRUE)) for (atac_on in c(FALSE, TRUE)) {
  wnn <- list(process = "WNN", WNN = list(RNA_dims = "1:55", ATAC_dims = "2:65",
    algorithm = 3, resolution = 0.8), RNA_processing = list(integrate_rna = rna_on),
    ATAC_processing = list(integrate_atac = atac_on))
  result <- read_task(wnn)
  stopifnot(result$RNA_processing$integrate_rna == rna_on,
            result$ATAC_processing$integrate_atac == atac_on,
            identical(result$WNN$ATAC_dims, 2:65))
}
bad <- wnn; bad$WNN$plot_point_size <- 0
expect_error(read_task(bad))
bad <- wnn; bad$WNN$lineage_markers <- list("Pou3f1", "Pou3f1")
expect_error(read_task(bad))
bad <- wnn; bad$WNN$lineage_markers <- list(42, "Foxa1")
expect_error(read_task(bad))
bad <- wnn; bad$WNN$lineage_markers <- list(label = "Foxa1")
expect_error(read_task(bad))
bad <- wnn; bad$WNN$lineage_markers <- list(" ")
expect_error(read_task(bad))
bad <- wnn; bad$WNN$lineage_assay <- ""
expect_error(read_task(bad))
bad <- wnn; bad$ATAC_processing$integrate_atac <- "false"
expect_error(read_task(bad))
bad <- wnn; bad$RNA_processing$RNA_dims <- "1:20"
expect_error(read_task(bad))
bad <- rna; bad$component_count <- 20
expect_error(read_task(bad))
bad <- rna; bad$component_count <- 1.5
expect_error(read_task(bad))
bad <- rna; bad$thresholds <- full$thresholds
expect_error(read_task(bad))
expect_error(read_task(rna, process = "WNN"))
bad <- review; bad$thresholds <- NULL
expect_error(read_task(bad))
# Direct script invocation accepts the same combined Nextflow parameter JSON.
jsonlite::write_json(full, file, auto_unbox = TRUE, null = "null")
stopifnot(identical(env$read_pipeline_config(file, process = "RNA_processing")$WNN$RNA_dims, 1:20))
stopifnot(!any(c("samples", "stage", "outdir", "macs3_path", "conda_env", "phase") %in%
              names(env$read_pipeline_config(file))))
# Optionally verify every settings file generated by a real Nextflow mock run.
args <- commandArgs(trailingOnly = TRUE)
if (length(args)) {
  files <- list.files(args[1], pattern = "^process_settings[.]json$", recursive = TRUE, full.names = TRUE)
  stopifnot(length(files) > 0)
  for (path in files) {
    cfg <- jsonlite::fromJSON(path, simplifyVector = FALSE)
    if (!is.null(cfg$process)) env$read_pipeline_config(path, "WT_1", process = cfg$process)
  }
  cat("Validated ", length(files), " generated task settings files.\n", sep = "")
}
unlink(file)
cat("All process-specific settings checks passed.\n")
